import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
const lab=path.dirname(fileURLToPath(import.meta.url));
const recovery=path.resolve(lab,'../../.git/priceyard-local-recovery-20261015/p00/runtime');
const {chromium}=await import(pathToFileURL(path.join(recovery,'npm-tools-309adbe095ff487cb1d6bd447c580c70/node_modules/playwright/index.mjs')));
const browser=await chromium.launch({headless:true,args:['--disable-background-networking','--disable-component-update','--disable-sync','--no-first-run']});
const origin='http://127.0.0.1:55446';
const context=await browser.newContext({extraHTTPHeaders:{'X-PriceYard-Test-Client':crypto.randomUUID()},serviceWorkers:'block'});
let outside=0;
await context.route('**/*',route=>{if(new URL(route.request().url()).origin===origin)return route.continue();outside++;return route.abort();});
await context.addInitScript(()=>localStorage.setItem('priceyard_onboarding_seen','1'));
const page=await context.newPage();
page.setDefaultTimeout(12000);
try {
  await page.goto(origin+'/login');
  await page.getByLabel('Email',{exact:true}).fill('free@example.com');
  await page.getByLabel('Password',{exact:true}).fill('PriceYardDemo8!');
  await page.getByRole('button',{name:'Log in',exact:true}).click();
  await page.waitForURL('**/dashboard');
  await page.getByRole('heading',{name:'Welcome, Test Free'}).waitFor();
  await page.goto(origin+'/__test__/push');
  await page.getByRole('button',{name:'Run safety checks',exact:true}).click();
  await page.waitForFunction(()=>window.__pushSafetyResult?.complete);
  const checks=await page.evaluate(()=>window.__pushSafetyResult);
  assert.equal(checks.passed,true);
  assert.deepEqual(checks.rejected_statuses,[422,422,422]);
  assert.equal(checks.valid_storage,204);
  assert.equal(checks.cleanup,204);
  assert.equal(checks.providers_disabled,true);
  assert.equal(outside,0);
  const report={checks,external_page_requests:outside,real_notification_deliveries:0,production_connections:0};
  fs.writeFileSync(path.join(lab,'runtime/push-checks.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report));
}finally{await browser.close();}
